EOF
echo "# tables" > "$dir/pkg/tables/README.md"
git -C "$dir" add -A && git -C "$dir" commit -q -m base
git -C "$dir" branch -q base_marker
subst 's/1\.25\.0/1.26.0/' "$dir/pkg/tables/gen.go"
git -C "$dir" add -A && git -C "$dir" commit -q -m "bump go version, no marker"
run_gate "$dir"
assert_rc "unmarked const value bump, no doc touch -> FAIL (regression)" "1" "$?"
rm -rf "$dir"

# --- The two recognizers must be independent, not exclusive ------------

# Fixture 10: a generated struct-literal row that ALSO carries the
# `// doc-gate:trivial` marker, bumped provenance-only -> OK. The marker
# path's `${line%%=*}` word-compare cannot accept a row with no top-level
# `=` (it compares the whole line, and the version token differs), so if a
# failed marker compare aborts the whole file instead of falling through,
# adding the marker makes a row STRICTER than the identical unmarked row in
# fixture 1 -- the marker would be a trap rather than a hint, and the
# "second, independent test" the checker's own header claims would in fact
# be exclusive (go-kure/.github#218 review, round 7).
dir="$(new_repo)"
mkdir -p "$dir/pkg/tables"
docs_map > "$dir/docs-map.yaml"
cat > "$dir/pkg/tables/zz_generated_tables.go" <<'EOF'
// Code generated by internal/gen; DO NOT EDIT.

package tables

var kinds = []KindInfo{
	{Group: "monitoring.coreos.com", Version: "v1", Kind: "Prometheus", ModuleVersion: "v0.93.1", Namespaced: true}, // doc-gate:trivial
}
EOF
echo "# tables" > "$dir/pkg/tables/README.md"
git -C "$dir" add -A && git -C "$dir" commit -q -m base
git -C "$dir" branch -q base_marker
subst 's/v0\.93\.1/v0.94.0/' "$dir/pkg/tables/zz_generated_tables.go"
git -C "$dir" add -A && git -C "$dir" commit -q -m "bump version on a marked row"
run_gate "$dir"
assert_rc "marked struct row, provenance-only bump -> OK" "0" "$?"
rm -rf "$dir"

# Fixture 11: the same marked row, but with Kind renamed as well -> FAIL.
# Isolation check for fixture 10: falling through from a failed marker
# compare must reach the provenance recognizer's STRICT rule, not bypass
# it. A marked row must be no more permissive than an unmarked one.
dir="$(new_repo)"
mkdir -p "$dir/pkg/tables"
docs_map > "$dir/docs-map.yaml"
cat > "$dir/pkg/tables/zz_generated_tables.go" <<'EOF'
// Code generated by internal/gen; DO NOT EDIT.

package tables

var kinds = []KindInfo{
	{Group: "monitoring.coreos.com", Version: "v1", Kind: "Prometheus", ModuleVersion: "v0.93.1", Namespaced: true}, // doc-gate:trivial
}
EOF
echo "# tables" > "$dir/pkg/tables/README.md"
git -C "$dir" add -A && git -C "$dir" commit -q -m base
git -C "$dir" branch -q base_marker
subst 's/Kind: "Prometheus"/Kind: "PrometheusAgent"/; s/v0\.93\.1/v0.94.0/' \
  "$dir/pkg/tables/zz_generated_tables.go"
git -C "$dir" add -A && git -C "$dir" commit -q -m "rename kind on a marked row"
run_gate "$dir"
assert_rc "marked struct row, kind renamed too -> FAIL" "1" "$?"
rm -rf "$dir"

# Fixture 12: a MARKED const whose identifier changes -> FAIL. This is the
# exact case the removed `|| return 1` used to reject outright, so it is the
# axis the round-7 fallthrough could regress: after falling through, the
# line must still be rejected by the provenance recognizer (a const carries
# no PROVENANCE_FIELDS field, so nothing can mask it equal).
dir="$(new_repo)"
mkdir -p "$dir/pkg/tables"
docs_map > "$dir/docs-map.yaml"
cat > "$dir/pkg/tables/gen.go" <<'EOF'
// Code generated by sync-versions.sh; DO NOT EDIT.

package tables

const GoVersion = "1.25.0" // doc-gate:trivial
EOF
echo "# tables" > "$dir/pkg/tables/README.md"
git -C "$dir" add -A && git -C "$dir" commit -q -m base
git -C "$dir" branch -q base_marker
subst 's/const GoVersion = "1\.25\.0"/const GoLangVersion = "1.26.0"/' \
  "$dir/pkg/tables/gen.go"
git -C "$dir" add -A && git -C "$dir" commit -q -m "rename a marked const"
run_gate "$dir"
assert_rc "marked const whose identifier changes -> FAIL" "1" "$?"
rm -rf "$dir"

echo "passed: $pass_count, failed: $failures"
[ "$failures" -eq 0 ]
